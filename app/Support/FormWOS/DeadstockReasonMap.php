    public static function description(?string $code, ?string $fallback = null): ?string
    {
        $code = trim((string) $code);
        $fallback = trim((string) $fallback);

        return self::all()[$code] ?? ($fallback !== '' && !self::isUnknownDescription($fallback) ? $fallback : null);
    }

    public static function isUnknownDescription(string $description): bool
    {
        $description = trim($description);

        return $description === ''
            || $description === '-'
            || str_contains($description, 'ยังไม่ระบุ');
    }
